// Offline fixtures exercise installer orchestration, not the official npm runtime.
//
// Fixture layout (all under one disposable directory):
//   tools/curl                  fake curl: serves the npm packument, the Node release
//                               index, per-version SHASUMS256.txt and per-version
//                               node archives, and delegates real HTTP probes to curl
//   fixtures/node-index.json    Node release index entries (every version is buildable)
//   fixtures/trees/node-vX.../  per-version Node tree whose bin/node is a wrapper that
//                               reports its fixture version for `--version` and execs
//                               the real Node otherwise; bin/npm is the fake npm
//   fixtures/generated/         node archives lazily generated by the fake curl
const fs = require('node:fs');
const path = require('node:path');
const os = require('node:os');
const crypto = require('node:crypto');
const net = require('node:net');
const assert = require('node:assert/strict');
const { execFileSync, spawn } = require('node:child_process');
const { test } = require('node:test');

const root = __dirname;
const testRoot = path.join(root, '.test-work');
fs.mkdirSync(testRoot, { recursive: true });

const arch = os.arch() === 'arm64' ? 'linux-arm64' : 'linux-x64';
const realCurl = execFileSync('which', ['curl'], { encoding: 'utf8' }).trim();
// Every version in the fixture node index gets a wrapper tree and a generated archive.
const nodeVersions = ['v22.23.4', 'v24.9.0', 'v26.0.0'];
const dshDefaultVersion = '1.0.0';

function run(command, args, env) {
  return new Promise(resolve => {
    const child = spawn(command, args, { cwd: root, env, stdio: ['ignore', 'pipe', 'pipe'] });
    let stdout = '';
    let stderr = '';
    child.stdout.on('data', chunk => { stdout += chunk; });
    child.stderr.on('data', chunk => { stderr += chunk; });
    const timer = setTimeout(() => child.kill('SIGKILL'), 30000);
    child.on('close', code => { clearTimeout(timer); resolve({ code, stdout, stderr }); });
  });
}

async function unusedPort() {
  const server = net.createServer();
  await new Promise(resolve => server.listen(0, '127.0.0.1', resolve));
  const port = server.address().port;
  await new Promise(resolve => server.close(resolve));
  return port;
}

function shellQuote(value) {
  return "'" + String(value).replace(/'/g, "'\\''") + "'";
}

